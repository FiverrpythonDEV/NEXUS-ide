export function useTranslation() {
  const { settings } = useAppContext();
  const lang = settings?.language || 'en';

  const t = (key: string): string => {
    const translation = translations[lang]?.[key] ?? translations['en']?.[key];
    return translation ?? key;
  };

  return { t, lang };
}
